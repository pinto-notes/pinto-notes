// Builds supabase/functions/mcp/automerge.gen.js: Automerge (and its WebAssembly, as base64) in one
// file, for the MCP server's shared notes (shared_notes.ts).
//   deno run -A scripts/build-automerge.ts
// Imported from npm, the function's bundle carried the whole package (45 MB, every build of the
// WebAssembly for every platform): the mcp eszip went from 18 MB to 66 MB. This file is 4.9 MB.
const VERSION = "3.5.0";
const root = new URL("..", import.meta.url).pathname;
const dir = await Deno.makeTempDir();
try {
  await Deno.writeTextFile(`${dir}/entry.ts`,
    `export * from "npm:@automerge/automerge@${VERSION}/slim";\nexport { automergeWasmBase64 } from "npm:@automerge/automerge@${VERSION}/automerge.wasm.base64";\n`);
  const out = await new Deno.Command(Deno.execPath(), { args: ["bundle", "--platform=browser", "--minify", "-o", `${dir}/out.js`, `${dir}/entry.ts`] }).output();
  if (!out.success) throw new Error(new TextDecoder().decode(out.stderr));
  const js = await Deno.readTextFile(`${dir}/out.js`);
  await Deno.writeTextFile(`${root}supabase/functions/mcp/automerge.gen.js`,
    `// @ts-self-types="./automerge.gen.d.ts"\n// Generated by scripts/build-automerge.ts (@automerge/automerge ${VERSION}). Don't edit.\n// deno-lint-ignore-file\n${js}`);
  console.log(`automerge.gen.js: ${(js.length / 1e6).toFixed(1)} MB`);
} finally {
  await Deno.remove(dir, { recursive: true });
}
