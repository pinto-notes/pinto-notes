-- A shared note's changes get their ids in the order they commit, so nothing commits behind a
-- device's pull cursor (docs/Technical/collaboration-design.md, "How it fits the app").
--
-- Before: an id was taken when the insert started. A change that took id 5 and committed after
-- another person's id 6 was invisible to a pull that saw 6; that device moved its cursor to 6 and
-- never asked for 5 again, and a snapshot with upto 6 then compacted 5 away though it wasn't in it:
-- the change was gone for every device that starts from the server. Shown with two real
-- connections in supabase/functions/mcp/collab_order.pg.test.ts.
--
-- Now each insert first takes the note's row (for no key update: inserts into one note queue
-- behind each other, while the foreign key checks of other tables don't wait), checks the key
-- generation again on the row it holds, and only then takes its id. The row is held until the
-- insert commits, so the next change on that note gets a larger id only after this one is
-- visible. A removal (collab_remove takes the row for update) also waits for changes in flight, so
-- none sealed under the old key commits after the key changed. Changes to different notes don't
-- wait for each other.
alter table public.note_updates alter column id set generated by default;

create or replace function public.collab_update_order() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  current_epoch int;
begin
  select epoch into current_epoch from public.shared_notes where id = new.note_id for no key update;
  if current_epoch is distinct from new.epoch then
    raise exception 'The note''s key changed. Open it again.' using errcode = 'PT409', hint = 'stale_epoch';
  end if;
  new.id := nextval(pg_get_serial_sequence('public.note_updates', 'id'));
  return new;
end $$;
revoke all on function public.collab_update_order() from public, anon, authenticated;

-- After note_updates_guard (triggers run in name order): roles and the first key check stay there.
drop trigger if exists note_updates_order on public.note_updates;
create trigger note_updates_order before insert on public.note_updates
  for each row execute function public.collab_update_order();
