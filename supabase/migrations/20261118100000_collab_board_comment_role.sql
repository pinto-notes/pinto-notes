-- Can comment on a shared whiteboard (18 November 2026; docs/Technical/collaboration-design.md,
-- section 8, "Can comment").
--
-- Until now a shared board's comments were in its Automerge document, sealed in the same changes
-- as the drawing. The server can't see inside a sealed change, so it couldn't let someone send
-- comments without letting them send drawing too. Comments now travel apart: `note_comments`, an
-- append-only list of sealed entries, one row per write (a new comment, a reply, an edit, a delete,
-- a resolve: the server can't tell which), in the order they commit:
--
--   `amb3c.<epoch>.<base64 nonce ‖ ct ‖ tag>`, AAD `amb3c|<note id>|<epoch>|<author id>`
--
-- A new role, commenter, writes there and nowhere else: every table of the drawing (note_updates,
-- note_snapshots, note_files) and the note's head and page keep taking only owners and editors, as
-- their guards and policies already say. A viewer writes neither. Each entry is stamped with its
-- writer (from the session, and in the seal's AAD) and their role, so devices read a record's words
-- only from its writer's entries, and trust a moved entry (the comments that were in the document,
-- with their writers) only from an owner or an editor.
--
-- What the server learns that it didn't: which sealed writes are comments, and that someone is a
-- commenter. Never what a comment says, where it is, which thread, or what kind of write it was.

-- 1. The role.
alter table public.note_members drop constraint if exists note_members_role_check;
alter table public.note_members add constraint note_members_role_check check (role in ('owner', 'editor', 'commenter', 'viewer'));
alter table public.note_invite_links drop constraint if exists note_invite_links_role_check;
alter table public.note_invite_links add constraint note_invite_links_role_check check (role in ('editor', 'commenter', 'viewer'));

-- Inviting with it (otherwise as in 20261104100200_collab_stale_key_answers.sql).
create or replace function public.collab_invite(p_note uuid, p_user uuid, p_role text, p_key_wrap text, p_epoch int) returns void
language plpgsql security definer set search_path = '' as $$
declare
  current_epoch int;
begin
  perform public.pane_take('write');
  if public.collab_role(p_note) is distinct from 'owner' then
    raise exception 'Only the owner can invite people to this note.' using errcode = '42501', hint = 'not_owner';
  end if;
  if p_role not in ('editor', 'commenter', 'viewer') then raise exception 'Unknown role.' using errcode = '22023'; end if;
  select epoch into current_epoch from public.shared_notes where id = p_note;
  if p_epoch <> current_epoch then
    raise exception 'The note''s key changed. Try again.' using errcode = 'PT409', hint = 'stale_epoch';
  end if;
  insert into public.note_members (note_id, user_id, role, epoch, key_wrap, wrapped_by, invited_by)
  values (p_note, p_user, p_role, p_epoch, p_key_wrap, auth.uid(), auth.uid())
  on conflict (note_id, user_id) do update set role = excluded.role;
end $$;

-- 2. The comment stream.
create table if not exists public.note_comments (
  id bigint generated by default as identity primary key,
  note_id uuid not null references public.shared_notes (id) on delete cascade,
  -- Who wrote it. Kept when they delete their account, as their changes are (20261107152300): the
  -- id is in the seal's AAD, needed to open it.
  author_id uuid not null default auth.uid(),
  -- Their role when they wrote it: devices trust a moved entry's writers only from an owner or editor.
  role text not null check (role in ('owner', 'editor', 'commenter')),
  epoch int not null,
  ct text not null check (octet_length(ct) <= 65536 and ct ~ '^amb3c\.[0-9]+\.[A-Za-z0-9+/]+={0,2}$'),
  -- Which AI wrote it, when one did (its client name); null for a person on a device.
  client text check (client is null or char_length(client) <= 100),
  created_at timestamptz not null default now()
);
create index if not exists note_comments_note on public.note_comments (note_id, id);

-- Before an entry goes in: the writer may comment, under the note's current key, in a box sealed for
-- it, with room left; then stamped. The note's row is taken first (as a change takes it,
-- 20261104100500), so ids on a note follow commit order and a pull after a cursor misses nothing.
create or replace function public.collab_comment_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  r text;
  current_epoch int;
  total bigint;
begin
  perform public.pane_take('write');
  r := public.collab_role(new.note_id);
  if r is null then
    raise exception 'You''re not in this note.' using errcode = '42501', hint = 'not_member';
  end if;
  if r not in ('owner', 'editor', 'commenter') then
    raise exception 'You can view this whiteboard but not comment on it.' using errcode = '42501', hint = 'read_only';
  end if;
  select epoch into current_epoch from public.shared_notes where id = new.note_id for no key update;
  if current_epoch is distinct from new.epoch then
    raise exception 'The note''s key changed. Open it again.' using errcode = 'PT409', hint = 'stale_epoch';
  end if;
  if split_part(new.ct, '.', 2) <> new.epoch::text then
    raise exception 'That comment isn''t sealed for this note''s key.' using errcode = '22023';
  end if;
  select coalesce(sum(octet_length(c.ct)), 0) into total from public.note_comments c where c.note_id = new.note_id;
  if total + octet_length(new.ct) > 16777216 then
    raise exception 'This whiteboard has no room for more comments.' using errcode = '54000', hint = 'comments_full';
  end if;
  new.id := nextval(pg_get_serial_sequence('public.note_comments', 'id'));
  new.author_id := auth.uid();
  new.role := r;
  new.created_at := now();
  -- An AI's entry says which AI (the file tools set pane.source = 'mcp'), as a change does.
  new.client := case when current_setting('pane.source', true) = 'mcp' then left(public.pane_writer(), 100) end;
  return new;
end $$;
revoke all on function public.collab_comment_guard() from public, anon, authenticated;
drop trigger if exists note_comments_guard on public.note_comments;
create trigger note_comments_guard before insert on public.note_comments
  for each row execute function public.collab_comment_guard();

alter table public.note_comments enable row level security;
drop policy if exists "members read" on public.note_comments;
create policy "members read" on public.note_comments for select to authenticated using (public.collab_role(note_id) is not null);
drop policy if exists "commenters add" on public.note_comments;
create policy "commenters add" on public.note_comments for insert to authenticated
  with check (public.collab_role(note_id) in ('owner', 'editor', 'commenter'));
revoke all on public.note_comments from anon, authenticated;
grant select on public.note_comments to authenticated;
grant insert (note_id, epoch, ct) on public.note_comments to authenticated;

do $$
