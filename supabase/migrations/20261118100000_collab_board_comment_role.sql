-- 3. A link reader who isn't signed in (20261117130000_collab_link_read.sql): the entries after
-- `p_after`, oldest first, 200 at a time (`more` says there are others), under the same proof.
create or replace function public.collab_link_comments(p_link text, p_answer text, p_after bigint default 0)
returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  n record;
  rows jsonb;
begin
  select * into n from public.collab_link_note(p_link, p_answer);
  select coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'author_id', c.author_id, 'role', c.role, 'epoch', c.epoch, 'ct', c.ct, 'client', c.client) order by c.id), '[]'::jsonb)
    into rows
    from (select * from public.note_comments c where c.note_id = n.note_id and c.id > coalesce(p_after, 0) order by c.id limit 200) c;
  return jsonb_build_object('comments', rows, 'more', jsonb_array_length(rows) = 200);
end $$;
revoke all on function public.collab_link_comments(text, text, bigint) from public;
grant execute on function public.collab_link_comments(text, text, bigint) to anon, authenticated;
